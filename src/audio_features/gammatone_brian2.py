"""Faithful port of the accou2023 (SPARRKULEE) dataset's actual gammatone cochleogram pipeline.

``legacy/accou_2023/feature_extraction.py`` (neural_tracking_across_spectrum) generated the
historical accou2023 audio features with ``brian2hears.Gammatone`` — Slaney's IIR gammatone
filter cascade — not the FIR/cosine-carrier approximation in ``gammatone.py``. That FIR
approximation has a real timing bug: ``fftconvolve(..., mode="same")`` crops around the impulse
response array's geometric midpoint rather than its actual (frequency-dependent) peak, introducing
a spurious 30-50ms non-causal advance per channel on top of the filter's true, much smaller
(0.5-15.6ms) group delay. IIR filtering sidesteps this entirely — it's causal by construction, so
there's no cropping-alignment question to get wrong.

Center frequencies are still generated by ``gammatone.erb_spaced_center_freqs`` rather than
``brian2hears.erbspace``: the two formulas differ only in which classic ERB-scale parametrization
they use (Moore's ``21.4*log10(...)`` vs. Glasberg-Moore's ``earQ``/``minBW`` form) and agree to
~1e-7 relative precision, so there's no reason to introduce a second center-frequency function.

Requires the optional ``gammatone-brian2`` dependency group (``brian2``, ``brian2hears``, and a
pinned ``numpy==2.2.5`` — ``brian2`` calls the ``ndarray.ptp()`` method that numpy>=2.3 removed).
Kept in a separate module, imported lazily, so the default (FIR-based) pipeline never requires
these heavier, version-pinned dependencies.
"""

from __future__ import annotations

import os

import numpy as np
from scipy.signal import resample_poly

from .gammatone import erb_spaced_center_freqs, gammatone_group_delay

_brian2_configured = False


def _configure_brian2() -> None:
    """Set up Cython code-gen caching and the runtime device, once per process.

    Matches ``legacy/accou_2023/feature_extraction.py``'s setup. Without this, ``Gammatone``
    recompiles from scratch on every call (~2s overhead just for a 2s test signal); with it,
    cached runs are roughly 50x faster than real-time (measured: 30s of audio in ~0.7s).
    """
    global _brian2_configured
    if _brian2_configured:
        return
    from brian2 import prefs, set_device

    cache_dir = os.path.expanduser("~/.cache/brian2_cache")
    os.makedirs(cache_dir, exist_ok=True)
    prefs.codegen.runtime.cython.cache_dir = cache_dir
    set_device("runtime")
    _brian2_configured = True


def _rectify_compress_and_align(
    subbands: np.ndarray,
    center_freqs: np.ndarray,
    fs: float,
    b: float,
    compression: float,
    remove_group_delay: bool,
) -> np.ndarray:
    """Shared per-chunk post-processing: optional group-delay alignment, then rectify + compress."""
    if remove_group_delay:
        aligned = np.zeros_like(subbands)
        for channel, center_freq in enumerate(center_freqs):
            delay_samples = int(round(gammatone_group_delay(center_freq, order=4, b_factor=b) * fs))
            n_remaining = subbands.shape[1] - delay_samples
            aligned[channel, :n_remaining] = subbands[channel, delay_samples:]
        subbands = aligned

    subbands = np.maximum(subbands, 0.0)
    return np.power(subbands, compression)


def brian2hears_gammatone_filterbank_envelopes(
    audio: np.ndarray,
    fs: float,
    target_fs: float,
    n_channels: int = 60,
    f_min: float = 50.0,
    f_max: float = 8000.0,
    b: float = 1.019,
    compression: float = 0.6,
    remove_group_delay: bool = False,
    chunk_seconds: float = 120.0,
    overlap_seconds: float = 1.0,
) -> tuple[np.ndarray, np.ndarray]:
    """Cochleogram via brian2hears' ``Gammatone`` (Slaney's IIR cascade) — the filter accou2023's
    features were actually generated with, in place of ``gammatone_filterbank_envelopes``'s FIR
    approximation. Same half-wave-rectify + power-law compression + resample steps, for a
    drop-in-compatible output contract.

    Being a proper causal IIR filter, this channel's output already peaks at its true, small
    (well under 20ms) gammatone group delay -- there's no cropping-alignment bug to fix here, the
    way there is in ``gammatone_filterbank_envelopes``. But that per-channel delay still varies
    with center frequency, so summing across channels still smears the result in time. Set
    remove_group_delay=True to shift each channel's output back by its own analytic peak delay
    (see ``gammatone_group_delay``), aligning every channel's impulse response to (approximately)
    the same sample before you collapse over the channel axis.

    ``Gammatone(...).process()`` materializes the whole signal for every channel at once (e.g. 60
    channels x a 20-minute recording at 30kHz is ~73GB peak RSS through rectify/compress/resample --
    enough to get OOM-killed on a well-provisioned machine). To bound memory, audio is processed in
    ``chunk_seconds``-long windows, each padded with ``overlap_seconds`` of context on both sides so
    the IIR filter settles before the kept region starts (the filter's own settling time is under
    ~100ms even for the lowest channel, so the default 1s margin is generous); only the non-overlap
    "core" of each chunk's rectified/compressed/resampled output is kept, so peak memory scales with
    chunk_seconds rather than the full recording's duration.

    Returns
    -------
    subband_envelopes : (n_channels, n_samples_out) ndarray
    center_freqs : (n_channels,) ndarray, Hz
    """
    audio = np.asarray(audio, dtype=float)
    if audio.ndim != 1:
        raise ValueError("audio must be a mono 1D waveform")

    _configure_brian2()
    from brian2 import Hz
    from brian2hears import Gammatone, Sound

    center_freqs = erb_spaced_center_freqs(f_min, f_max, n_channels)
    up, down = int(round(target_fs)), int(round(fs))

    n_samples = audio.size
    chunk_samples = max(1, int(round(chunk_seconds * fs)))
    overlap_samples = int(round(overlap_seconds * fs))
    n_out_total = -(-(n_samples * up) // down)  # ceil, matching resample_poly's own output length

    subband_envelopes = np.empty((n_channels, n_out_total), dtype=float)

    core_start = 0
    out_core_start = 0
    while core_start < n_samples:
        core_end = min(core_start + chunk_samples, n_samples)
        is_last_chunk = core_end == n_samples
        ext_start = max(0, core_start - overlap_samples)
        ext_end = min(n_samples, core_end + overlap_samples)

        sound = Sound(audio[ext_start:ext_end], fs * Hz)
        chunk_subbands = Gammatone(sound, center_freqs, b=b).process().T  # (n_channels, ext_len)
        chunk_subbands = _rectify_compress_and_align(
            chunk_subbands, center_freqs, fs, b, compression, remove_group_delay
        )
        chunk_resampled = resample_poly(chunk_subbands, up, down, axis=-1)

        # Keep only the samples corresponding to [core_start, core_end) -- i.e. drop the
        # settling-time padding -- located within this chunk's own (locally-indexed) output.
        local_out_start = round((core_start - ext_start) * up / down)
        out_core_end = n_out_total if is_last_chunk else round(core_end * up / down)
        n_keep = out_core_end - out_core_start

        subband_envelopes[:, out_core_start:out_core_end] = chunk_resampled[
            :, local_out_start : local_out_start + n_keep
        ]

        core_start = core_end
        out_core_start = out_core_end

    return subband_envelopes, center_freqs
